let maths = 80;
let science = 90;
let english = 70;

// Addition
let total = maths + science + english;

// Subtraction
let difference = science - maths;

// Multiplication
let doubleMarks = maths * 2;

// Division
let percentage = total / 3;

// Modulus
let remainder = total % 3;

// Exponentiation
let square = maths ** 2;

// Increment
let bonusMarks = maths;
bonusMarks++;

// Decrement
let reducedMarks = science;
reducedMarks--;

console.log("Total Marks:", total);
console.log("Difference:", difference);
console.log("Double Maths Marks:", doubleMarks);
console.log("Percentage:", percentage);
console.log("Remainder:", remainder);
console.log("Maths Square:", square);
console.log("Bonus Marks:", bonusMarks);
console.log("Reduced Science Marks:", reducedMarks);